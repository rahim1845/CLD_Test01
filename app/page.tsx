"use client";

import { useRef, type ReactNode } from "react";
import { CodeXml, PanelsTopLeft, SwatchBook } from "lucide-react";
import { useThemeStore, type Engine, type PreviewTab } from "@/store/themeStore";
import ThemeSync from "@/components/ThemeSync";
import ThemeNameEditor from "@/components/ThemeNameEditor";
import InputPanel from "@/components/generator/InputPanel";
import PreviewContainer from "@/components/preview/PreviewContainer";
import TokensPanel from "@/components/tokens/TokensPanel";
import ExportsPanel from "@/components/exports/ExportsPanel";
import { Badge, type BadgeTone } from "@/components/ui/Badge";
import { LogoMark } from "@/components/ui/LogoMark";
import { SegmentedControl, type SegmentedOption } from "@/components/ui/SegmentedControl";
import { Tooltip } from "@/components/ui/Tooltip";
import { useHotkeys } from "@/components/ui/useHotkeys";

const TAB_ID_PREFIX = "tf-view";

const TABS: SegmentedOption<PreviewTab>[] = [
  { value: "preview", label: "Preview", icon: PanelsTopLeft, tooltip: "Live preview", shortcut: "1" },
  { value: "tokens", label: "Tokens", icon: SwatchBook, tooltip: "All tokens", shortcut: "2" },
  { value: "exports", label: "Export", icon: CodeXml, tooltip: "Export code", shortcut: "3" },
];

const PANELS: Record<PreviewTab, () => ReactNode> = {
  preview: () => <PreviewContainer />,
  tokens: () => <TokensPanel />,
  exports: () => <ExportsPanel />,
};

const ENGINES: Record<Engine, { label: string; tone: BadgeTone; hint: string }> = {
  local: {
    label: "Instant engine",
    tone: "success",
    hint: "Deterministic, math-based generator. Runs in your browser with no API key.",
  },
  ai: {
    label: "Claude AI",
    tone: "accent",
    hint: "Generated by Claude through the Anthropic API.",
  },
};

const DESKTOP_QUERY = "(min-width: 1024px)";

function EngineBadge() {
  const engine = useThemeStore((s) => s.engine);
  const isGenerating = useThemeStore((s) => s.isGenerating);
  const meta = ENGINES[engine];

  return (
    <Tooltip content={isGenerating ? "Generating your theme" : meta.hint} side="bottom" align="end">
      <Badge tone={meta.tone} dot pulse={isGenerating} aria-live="polite">
        {isGenerating ? "Generating" : meta.label}
      </Badge>
    </Tooltip>
  );
}

function BreadcrumbSlash({ className }: { className?: string }) {
  return (
    <svg width="16" height="16" viewBox="0 0 16 16" fill="none" aria-hidden className={className}>
      <path d="M10.25 2.75 5.75 13.25" stroke="currentColor" strokeWidth="1.25" strokeLinecap="round" />
    </svg>
  );
}

export default function Home() {
  const activeTab = useThemeStore((s) => s.activeTab);
  const setActiveTab = useThemeStore((s) => s.setActiveTab);
  const mainRef = useRef<HTMLElement>(null);

  const selectTab = (tab: PreviewTab, reveal: boolean) => {
    setActiveTab(tab);
    if (!reveal || window.matchMedia(DESKTOP_QUERY).matches) return;
    const main = mainRef.current;
    if (!main) return;
    const header = document.getElementById("tf-header");
    const headerBottom = header?.getBoundingClientRect().bottom ?? 0;
    if (main.getBoundingClientRect().top > headerBottom + 1) {
      const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
      main.scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "start" });
    }
  };

  useHotkeys({
    "1": () => selectTab("preview", false),
    "2": () => selectTab("tokens", false),
    "3": () => selectTab("exports", false),
  });

  return (
    <>
      <ThemeSync />
      <div className="flex min-h-dvh flex-col text-[var(--shell-text)] lg:h-dvh lg:min-h-0 lg:overflow-hidden">
        <header
          id="tf-header"
          className={
            "shell-header sticky top-0 z-30 shrink-0 border-b border-[var(--shell-border)] " +
            "bg-[rgba(8,8,11,0.86)] backdrop-blur-xl backdrop-saturate-150 " +
            "lg:relative lg:bg-[var(--shell-bg)] lg:backdrop-blur-none"
          }
        >
          <div className="flex items-center gap-2 pl-4 [grid-area:brand] sm:pl-5 lg:gap-2.5 lg:border-r lg:border-[var(--shell-border)] lg:bg-[var(--shell-panel)]">
            <div className="flex items-center gap-2.5">
              <LogoMark size={22} className="shrink-0" />
              <span className="hidden text-[13.5px] font-semibold tracking-[-0.015em] text-[var(--shell-text)] sm:inline">
                ThemeForge
              </span>
            </div>
            <BreadcrumbSlash className="shrink-0 text-[var(--shell-text-subtle)] opacity-60 lg:hidden" />
          </div>

          <div className="flex min-w-0 items-center pr-2 [grid-area:name] lg:pl-3">
            <ThemeNameEditor />
          </div>

          <div className="flex items-center justify-center px-4 pb-3 [grid-area:tabs] sm:px-5 lg:p-0">
            <SegmentedControl
              aria-label="Workspace views"
              semantics="tablist"
              idPrefix={TAB_ID_PREFIX}
              options={TABS}
              value={activeTab}
              onChange={(tab) => selectTab(tab, true)}
              className="w-full sm:max-w-[400px] lg:w-auto"
            />
          </div>

          <div className="flex items-center justify-end pr-4 [grid-area:engine] sm:pr-5">
            <EngineBadge />
          </div>
        </header>

        <div className="flex flex-1 flex-col lg:min-h-0 lg:flex-row">
          <aside
            aria-label="Theme generator"
            className={
              "border-b border-[var(--shell-border)] bg-[var(--shell-panel)] " +
              "lg:w-[var(--shell-sidebar-w)] lg:shrink-0 lg:overflow-y-auto lg:overscroll-contain " +
              "lg:border-b-0 lg:border-r"
            }
          >
            <div className="flex min-h-full flex-col px-4 py-5 sm:px-5">
              <InputPanel />
            </div>
          </aside>

          <main
            ref={mainRef}
            className="shell-main shell-canvas flex min-w-0 shrink-0 flex-col overflow-hidden lg:flex-1"
          >
            <div
              key={activeTab}
              role="tabpanel"
              id={`${TAB_ID_PREFIX}-panel-${activeTab}`}
              aria-labelledby={`${TAB_ID_PREFIX}-tab-${activeTab}`}
              className="shell-panel-in absolute inset-0 flex flex-col overflow-hidden"
            >
              {PANELS[activeTab]()}
            </div>
          </main>
        </div>
      </div>
    </>
  );
}
